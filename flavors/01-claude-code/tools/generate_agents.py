"""Generate the Claude Code subagents and the runtime data files from core/.

Generated outputs:
    .claude/agents/<id>.md                      one subagent per satellite
    .claude/vegapunk/punk-records.schema.json   byte-for-byte copy of core/schemas/
    .claude/vegapunk/event.schema.json          byte-for-byte copy of core/schemas/
    .claude/vegapunk/roles.json                 reads/writes/active_phases per role
    .claude/skills/vegapunk/SKILL.md            the /vegapunk engine skill, from
                                                templates/skill-vegapunk.md + Part B of stella.md
The hand-written .claude/vegapunk/punk_records.py is never touched or checked.

Usage:
    python generate_agents.py          # write the files
    python generate_agents.py --check  # compare only; exit 1 on any difference

Paths are resolved relative to this script, so it works from any directory.
"""
from __future__ import annotations

import argparse
import json
import posixpath
import re
import sys
from pathlib import Path

import yaml

FLAVOR_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = FLAVOR_DIR.parent.parent
PROMPTS_DIR = REPO_ROOT / "core" / "prompts"
CONFIG_PATH = FLAVOR_DIR / "agents.config.yaml"
OUT_DIR = FLAVOR_DIR / ".claude" / "agents"
RUNTIME_DIR = FLAVOR_DIR / ".claude" / "vegapunk"
SKILLS_DIR = FLAVOR_DIR / ".claude" / "skills"
SKILL_TEMPLATE = FLAVOR_DIR / "templates" / "skill-vegapunk.md"
SKILL_MARKER = "{{STELLA_COORDINATOR}}"
STELLA_PART_B_HEADING = "## Part B"
REPO_BLOB_URL = "https://github.com/ckomiya/vegapunk-agents/blob/main/"
MD_LINK_RE = re.compile(r"(\]\()([^)\s]+)(\))")
SCHEMAS_DIR = REPO_ROOT / "core" / "schemas"
SCHEMA_FILES = ["punk-records.schema.json", "event.schema.json"]
MANUAL_RUNTIME_FILES = {"punk_records.py"}

SATELLITE_IDS = [
    "punk-01-shaka",
    "punk-02-lilith",
    "punk-03-edison",
    "punk-04-pythagoras",
    "punk-05-atlas",
    "punk-06-york",
]
ROLE_IDS = ["stella", *SATELLITE_IDS]
ROLE_KEYS = ("reads", "writes", "active_phases")
MODEL_ALIASES = {"haiku", "sonnet", "opus", "fable", "inherit"}
COLORS = {"red", "blue", "green", "yellow", "purple", "orange", "pink", "cyan"}
EFFORT_LEVELS = ("low", "medium", "high", "xhigh", "max")
ALLOWED_TOOLS = {"Read", "Grep", "Glob", "Edit", "Write", "Bash", "WebSearch", "WebFetch"}

HEADER = (
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Copyright 2026 Christian Gonzales Komiya\n"
    "# GENERATED by flavors/01-claude-code/tools/generate_agents.py\n"
    "# from core/prompts/. Do not edit by hand: edit core/ or\n"
    "# agents.config.yaml and regenerate.\n"
)

SKILL_HEADER = (
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Copyright 2026 Christian Gonzales Komiya\n"
    "# GENERATED by flavors/01-claude-code/tools/generate_agents.py\n"
    "# from templates/skill-vegapunk.md and core/prompts/stella.md.\n"
    "# Do not edit by hand: edit the template or core/ and regenerate.\n"
)


class GenError(Exception):
    pass


def read_text(path: Path) -> str:
    with open(path, encoding="utf-8", newline="") as fh:
        return fh.read().replace("\r\n", "\n")


def rel(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def split_front_matter(text: str, path: Path) -> tuple[dict, str]:
    lines = text.split("\n")
    if not lines or lines[0] != "---":
        raise GenError(f"{rel(path)}: must start with '---' on line 1")
    try:
        end = lines.index("---", 1)
    except ValueError:
        raise GenError(f"{rel(path)}: front matter is not closed") from None
    meta = yaml.safe_load("\n".join(lines[1:end])) or {}
    return meta, "\n".join(lines[end + 1:])


def shared_body() -> str:
    """Body of _shared-protocol.md without the leading HTML SPDX/copyright comments."""
    lines = read_text(PROMPTS_DIR / "_shared-protocol.md").split("\n")
    i = 0
    while i < len(lines) and (lines[i].startswith("<!--") or lines[i].strip() == ""):
        i += 1
    return "\n".join(lines[i:]).rstrip("\n")


def load_config() -> dict:
    cfg = yaml.safe_load(read_text(CONFIG_PATH)) or {}
    engine = cfg.get("engine")
    if not isinstance(engine, dict):
        raise GenError(f"{rel(CONFIG_PATH)}: missing 'engine' mapping")
    if engine.get("effort") not in EFFORT_LEVELS:
        raise GenError(
            f"engine: invalid effort {engine.get('effort')!r} (use one of {list(EFFORT_LEVELS)})"
        )
    sats = cfg.get("satellites")
    if not isinstance(sats, dict):
        raise GenError(f"{rel(CONFIG_PATH)}: missing 'satellites' mapping")
    if set(sats) != set(SATELLITE_IDS):
        raise GenError(
            f"{rel(CONFIG_PATH)}: satellites must be exactly {SATELLITE_IDS}; got {sorted(sats)}"
        )
    for sid, c in sats.items():
        if not isinstance(c, dict):
            raise GenError(f"{sid}: config must be a mapping")
        missing = {"model", "color", "maxTurns", "tools"} - set(c)
        if missing:
            raise GenError(f"{sid}: missing config keys {sorted(missing)}")
        model = c["model"]
        if not (isinstance(model, str) and (model in MODEL_ALIASES or model.startswith("claude-"))):
            raise GenError(
                f"{sid}: invalid model {model!r} "
                f"(use one of {sorted(MODEL_ALIASES)} or an ID starting with 'claude-')"
            )
        if c["color"] not in COLORS:
            raise GenError(f"{sid}: invalid color {c['color']!r} (use one of {sorted(COLORS)})")
        mt = c["maxTurns"]
        if isinstance(mt, bool) or not isinstance(mt, int) or mt <= 0:
            raise GenError(f"{sid}: maxTurns must be an integer > 0, got {mt!r}")
        tools = c["tools"]
        if not isinstance(tools, list) or not tools or not all(isinstance(t, str) for t in tools):
            raise GenError(f"{sid}: tools must be a non-empty list of tool names")
        if "Agent" in tools:
            raise GenError(f"{sid}: 'Agent' must never be in tools")
        bad = [t for t in tools if t not in ALLOWED_TOOLS]
        if bad:
            raise GenError(f"{sid}: unsupported tools {bad} (allowed: {sorted(ALLOWED_TOOLS)})")
    return cfg


def render(sid: str, conf: dict, shared: str) -> str:
    src = PROMPTS_DIR / f"{sid}.md"
    meta, body = split_front_matter(read_text(src), src)
    if meta.get("id") != sid:
        raise GenError(f"{rel(src)}: front matter id is {meta.get('id')!r}, expected {sid!r}")
    for key in ("name", "role"):
        if not meta.get(key):
            raise GenError(f"{rel(src)}: front matter lacks '{key}'")
    description = (
        f"{meta['name']} — {meta['role']}. Vegapunk satellite. Invoked only by "
        "the /vegapunk engine with a mission context; returns JSON record "
        "drafts. Do not use for general tasks."
    )
    front = (
        "---\n"
        + HEADER
        + f"name: {sid}\n"
        # A JSON string is a valid single-line YAML double-quoted scalar.
        + f"description: {json.dumps(description, ensure_ascii=False)}\n"
        + f"tools: {', '.join(conf['tools'])}\n"
        + "disallowedTools: Agent\n"
        + f"model: {conf['model']}\n"
        + f"color: {conf['color']}\n"
        + f"maxTurns: {conf['maxTurns']}\n"
        + "omitClaudeMd: true\n"
        + "---\n"
    )
    return front + "\n" + shared + "\n\n" + body.strip("\n") + "\n"


def absolutize_links(text: str, source: Path) -> str:
    """Rewrite relative Markdown link targets to absolute GitHub URLs (text is untouched)."""
    base = posixpath.dirname(rel(source))

    def repl(match: re.Match) -> str:
        target = match.group(2)
        if target.startswith("#") or re.match(r"^[A-Za-z][A-Za-z0-9+.-]*:", target) or target.startswith("//"):
            return match.group(0)
        path_part, sep, anchor = target.partition("#")
        resolved = posixpath.normpath(posixpath.join(base, path_part))
        if resolved.startswith("..") or not (REPO_ROOT / resolved).is_file():
            raise GenError(f"{rel(source)}: relative link {target!r} does not resolve to a file in the repo")
        return f"{match.group(1)}{REPO_BLOB_URL}{resolved}{sep}{anchor}{match.group(3)}"

    return MD_LINK_RE.sub(repl, text)


def stella_part_b() -> str:
    """Text of stella.md from the '## Part B' heading to the end of the file, as is."""
    path = PROMPTS_DIR / "stella.md"
    lines = read_text(path).split("\n")
    for i, line in enumerate(lines):
        if line.startswith(STELLA_PART_B_HEADING):
            return absolutize_links("\n".join(lines[i:]).rstrip("\n"), path)
    raise GenError(f"{rel(path)}: no '{STELLA_PART_B_HEADING}' heading found")


def build_skill(effort: str) -> str:
    """SKILL.md text: front matter + template body with Part B of stella.md substituted."""
    lines = read_text(SKILL_TEMPLATE).split("\n")
    i = 0
    if lines and lines[0].startswith("<!--"):
        while i < len(lines) and "-->" not in lines[i]:
            i += 1
        i += 1  # skip the line that closes the SPDX comment
    while i < len(lines) and lines[i].strip() == "":
        i += 1
    body_lines = lines[i:]
    count = sum(1 for line in body_lines if line.strip() == SKILL_MARKER)
    total = "\n".join(body_lines).count(SKILL_MARKER)
    if count == 0:
        raise GenError(f"{rel(SKILL_TEMPLATE)}: marker {SKILL_MARKER} not found on its own line")
    if count > 1 or total != count:
        raise GenError(f"{rel(SKILL_TEMPLATE)}: marker {SKILL_MARKER} must appear exactly once")
    part_b = stella_part_b()
    body = "\n".join(part_b if line.strip() == SKILL_MARKER else line for line in body_lines)
    description = (
        "Run a vegapunk-agents mission (Multi-Agent Architecture Pattern) with the "
        "punk-01…punk-06 satellites and Punk Records. Use only when the user invokes /vegapunk."
    )
    front = (
        "---\n"
        + SKILL_HEADER
        + "name: vegapunk\n"
        + f"description: {json.dumps(description, ensure_ascii=False)}\n"
        + "argument-hint: [mission goal]\n"
        + f"effort: {effort}\n"
        + "disable-model-invocation: true\n"
        + "allowed-tools: Bash(python .claude/vegapunk/punk_records.py *)\n"
        + "---\n"
    )
    return front + "\n" + body.rstrip("\n") + "\n"


def build_roles() -> str:
    """roles.json text: reads/writes/active_phases of every role, from core/prompts front matter."""
    roles: dict = {
        "$comment": "SPDX-License-Identifier: Apache-2.0 | Copyright 2026 Christian Gonzales Komiya",
        "_generated": (
            "GENERATED by flavors/01-claude-code/tools/generate_agents.py from the front "
            "matter of core/prompts/*.md. Do not edit by hand: edit core/ and regenerate."
        ),
    }
    for rid in ROLE_IDS:
        src = PROMPTS_DIR / f"{rid}.md"
        meta, _ = split_front_matter(read_text(src), src)
        if meta.get("id") != rid:
            raise GenError(f"{rel(src)}: front matter id is {meta.get('id')!r}, expected {rid!r}")
        entry = {}
        for key in ROLE_KEYS:
            value = meta.get(key)
            if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
                raise GenError(f"{rel(src)}: front matter '{key}' must be a list of strings")
            entry[key] = value
        roles[rid] = entry
    return json.dumps(roles, indent=2, ensure_ascii=False) + "\n"


def expected_outputs(cfg: dict) -> dict[Path, bytes]:
    """Every generated file (absolute path -> exact bytes)."""
    sats = cfg["satellites"]
    shared = shared_body()
    out: dict[Path, bytes] = {}
    for sid in SATELLITE_IDS:
        out[OUT_DIR / f"{sid}.md"] = render(sid, sats[sid], shared).encode("utf-8")
    for name in SCHEMA_FILES:
        out[RUNTIME_DIR / name] = (SCHEMAS_DIR / name).read_bytes()
    out[RUNTIME_DIR / "roles.json"] = build_roles().encode("utf-8")
    out[SKILLS_DIR / "vegapunk" / "SKILL.md"] = build_skill(cfg["engine"]["effort"]).encode("utf-8")
    return out


def existing_files(directory: Path, ignore: set[str] = frozenset(), recursive: bool = False) -> set[Path]:
    if not directory.is_dir():
        return set()
    it = directory.rglob("*") if recursive else directory.iterdir()
    return {p for p in it if p.is_file() and p.name not in ignore}


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate Claude Code subagents from core/prompts/.")
    ap.add_argument("--check", action="store_true", help="compare only; exit 1 on differences")
    args = ap.parse_args()
    try:
        expected = expected_outputs(load_config())
    except (GenError, OSError, yaml.YAMLError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.check:
        problems = []
        for path, data in expected.items():
            if not path.is_file():
                problems.append(f"missing:    {rel(path)}")
            elif path.read_bytes() != data:
                problems.append(f"different:  {rel(path)}")
        extras = existing_files(OUT_DIR) | existing_files(RUNTIME_DIR, MANUAL_RUNTIME_FILES)
        extras |= existing_files(SKILLS_DIR, recursive=True)
        for path in sorted(extras - set(expected)):
            problems.append(f"unexpected: {rel(path)}")
        if problems:
            print("Generated files are out of date; regenerate with generate_agents.py:")
            print("\n".join(problems))
            return 1
        print(f"OK: {len(expected)} generated files up to date (agents + .claude/vegapunk + skill)")
        return 0

    for path, data in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"Wrote {len(expected)} generated files to {rel(OUT_DIR)} and {rel(RUNTIME_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
